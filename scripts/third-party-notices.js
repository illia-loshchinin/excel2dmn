// Writes THIRD-PARTY-NOTICES.txt from the production dependency tree.
// Uses license-checker for discovery but formats the output itself so the file
// is portable (no local paths) and deterministic across machines.
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import checker from 'license-checker';

const root = new URL('..', import.meta.url).pathname;
const self = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));

checker.init({ start: root, production: true }, (err, packages) => {
  if (err) throw err;
  const sections = Object.keys(packages)
    .filter((id) => id !== `${self.name}@${self.version}`)
    .sort()
    .map((id) => {
      const p = packages[id];
      const lines = [id, `License: ${p.licenses}`];
      if (p.repository) lines.push(`Repository: ${p.repository}`);
      // license-checker falls back to the README when a package ships no license
      // file; only embed real license texts.
      if (p.licenseFile && /^(licen[cs]e|copying)/i.test(basename(p.licenseFile))) {
        lines.push('', readFileSync(p.licenseFile, 'utf8').trim());
      }
      return lines.join('\n');
    });
  const header =
    `${self.name} bundles the following third-party packages.\n` +
    'Generated by `npm run licenses:notices`; do not edit by hand.';
  writeFileSync(
    new URL('../THIRD-PARTY-NOTICES.txt', import.meta.url),
    [header, ...sections].join(`\n\n${'-'.repeat(78)}\n\n`) + '\n',
  );
});
